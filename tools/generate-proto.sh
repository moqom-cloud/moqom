#!/usr/bin/env bash
#
# Regenerate everything derived from proto/.
#
# Generated code is committed rather than produced at build time. The argument
# for generating on the fly is that it cannot go stale; the argument against is
# that it puts protoc and two plugins between a customer and `go get`, and a Go
# SDK that needs a code generator installed to compile is not a Go SDK. CI runs
# this and fails on a diff, which buys the same guarantee without the cost.
#
# Requires protoc. The Go plugins are installed here at pinned versions, into
# .tools/bin, so the output does not depend on what happens to be on a PATH.
#
# The admin API's Go output lands in the SDK, which is a repository of its own --
# a Go import path is a URL, so an SDK is only consumable from a repository named
# after it. MOQOM_GO_SDK says where that checkout is; the default assumes a
# sibling, which is where it lands if you cloned both into the same directory.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

go_sdk="${MOQOM_GO_SDK:-$root/../moqom-go}"
if [[ ! -d "$go_sdk" ]]; then
  echo "no Go SDK at $go_sdk" >&2
  echo "check out moqom-go beside this repository, or set MOQOM_GO_SDK." >&2
  exit 1
fi
go_sdk="$(cd "$go_sdk" && pwd)"

readonly PROTOC_GEN_GO=v1.36.6
readonly PROTOC_GEN_GO_GRPC=v1.5.1

tools="$root/.tools/bin"
mkdir -p "$tools"

if [[ ! -x "$tools/protoc-gen-go" ]]; then
  GOBIN="$tools" go install "google.golang.org/protobuf/cmd/protoc-gen-go@$PROTOC_GEN_GO"
fi
if [[ ! -x "$tools/protoc-gen-go-grpc" ]]; then
  GOBIN="$tools" go install "google.golang.org/grpc/cmd/protoc-gen-go-grpc@$PROTOC_GEN_GO_GRPC"
fi

export PATH="$tools:$PATH"

# Both Go outputs use paths=source_relative against a per-tree output root, so
# the file layout follows the go_package option rather than the proto package.
# The admin API lands in the SDK module because customers need those types; the
# relay link lands in the control plane's internal tree because nobody outside
# it may import it, which Go enforces for any path containing `internal`.
protoc --proto_path=proto \
  --go_out="$go_sdk" --go_opt=module=github.com/moqom-cloud/moqom-go \
  --go-grpc_out="$go_sdk" --go-grpc_opt=module=github.com/moqom-cloud/moqom-go \
  proto/moqom/admin/v1/*.proto

protoc --proto_path=proto \
  --go_out=go --go_opt=module=github.com/moqom-cloud/moqom/go \
  --go-grpc_out=go --go-grpc_opt=module=github.com/moqom-cloud/moqom/go \
  proto/moqom/relay/v1/*.proto

# The recorder link, internal for the same reason as the relay link.
protoc --proto_path=proto \
  --go_out=go --go_opt=module=github.com/moqom-cloud/moqom/go \
  --go-grpc_out=go --go-grpc_opt=module=github.com/moqom-cloud/moqom/go \
  proto/moqom/recorder/v1/*.proto

# Customer relay enrolments on the overlay, internal until the admin API takes
# them on.
protoc --proto_path=proto \
  --go_out=go --go_opt=module=github.com/moqom-cloud/moqom/go \
  --go-grpc_out=go --go-grpc_opt=module=github.com/moqom-cloud/moqom/go \
  proto/moqom/byoc/v1/*.proto

# Rust is generated by tonic-build from the SDK's own build.rs, at compile time
# rather than here: cargo already requires a build for anything, so a generator
# in the build graph costs a dependency rather than a workflow step, and it
# cannot go stale. It finds this directory the same way, via MOQOM_PROTO_ROOT or
# a sibling checkout.
echo "generated: $go_sdk/admin/adminpb, go/internal/relaypb, go/internal/recorderpb, go/internal/byocpb"
